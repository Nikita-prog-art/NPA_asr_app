#!/usr/bin/env python3
"""Bake models/manifest.json into the binary as the compiled-in fallback
catalogue, so a fresh install knows the official model URLs even offline.

Usage: tools/make_manifest_header.py [models/manifest.json] [src/net/manifest_builtin_data.h]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

TEMPLATE = """// Generated by tools/make_manifest_header.py - do not edit by hand.
//
// Compiled-in copy of models/manifest.json: used when the remote manifest cannot
// be fetched (offline installs, GitHub outage).
#pragma once

namespace asr::net {{

inline constexpr const char * kBuiltinManifestJson = R"JSON({json})JSON";

}}  // namespace asr::net
"""


def main() -> int:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "models/manifest.json"
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "src/net/manifest_builtin_data.h"
    if src.exists():
        data = json.loads(src.read_text())
    else:
        data = {"schema": 1, "models": []}
    text = json.dumps(data, indent=2, ensure_ascii=False)
    if ")JSON" in text:
        print("manifest contains the raw-string terminator, aborting", file=sys.stderr)
        return 1
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(TEMPLATE.format(json=text))
    n = sum(len(m.get("files", [])) for m in data.get("models", []))
    print(f"wrote {dst}: {len(data.get('models', []))} model(s), {n} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
